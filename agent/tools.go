type hintItem struct {
	Text        string            `json:"text"`
	AssetIDs    []json.RawMessage `json:"asset_ids"`
	TrafficRefs []db.TrafficRef   `json:"traffic_refs"`
}

// addOneHint attaches one hint node (active/human) to the exploration graph, optionally anchored to assets, and returns the id.
func (t *ToolSet) addOneHint(it hintItem) (int64, error) {
	if len(it.TrafficRefs) > 0 && !findingTrafficBindingEnabled() {
		return 0, fmt.Errorf("automatic traffic binding by the agent is off, so a hint carrying traffic_refs was not saved; enable it in the system settings, or hand over text only")
	}
	if strings.TrimSpace(it.Text) == "" {
		return 0, fmt.Errorf("text must not be empty")
	}
	var anchors []int64
	for _, raw := range it.AssetIDs {
		if tid := pid(raw); tid > 0 {
			anchors = append(anchors, tid)
		}
	}
	refs, err := db.NormalizeTrafficRefs(it.TrafficRefs)
	if err != nil {
		return 0, err
	}
	payload := map[string]any{"text": it.Text}
	if len(refs) > 0 {
		payload["traffic_refs"] = refs
	}
	// Waking the planner is not done per entry here -- addHint triggers it once after the whole batch is
	// written (carrying the hint text), so one add_hint with several hints does not flood the planner's trigger rows.
	return t.ts.AddNode(db.KindHint, payload, 0, "active", "human", anchors)
}

type goalItem struct {
	Text      string `json:"text"`
	VulnClass string `json:"vulnclass"`
}

// addOneGoal attaches one goal node (open) to the exploration graph, linked to the task root (the origin fact, rel spawns).
// origin comes from t.worker (defaulting to system): what the goal decomposer writes is recorded as
// "goals", and what the main agent writes at runtime as "human". Waking the planner is done once by
// setGoals after the whole batch is written (see below); this only persists.
func (t *ToolSet) addOneGoal(it goalItem) (int64, error) {
	text := strings.TrimSpace(it.Text)
	if text == "" {
		return 0, fmt.Errorf("text must not be empty")
	}
	payload := map[string]any{"text": text}
	if vc := strings.TrimSpace(it.VulnClass); vc != "" {
		payload["vulnclass"] = vc
	}
	origin := t.worker
	if origin == "" {
		origin = "system"
	}
	id, err := t.ts.AddNode(db.KindGoal, payload, 0, "open", origin, nil)
	if err != nil {
		return 0, err
	}
	if of, _ := t.ts.OriginFactID(); of > 0 && id > 0 {
		_ = t.ts.Link(of, db.RelSpawns, id) // goals descend from the task root (origin fact)
	}
	return id, nil
}

// setGoals adds exploration goals (goal nodes) to [this task]. It is both the goal decomposer's
// submission tool and the main agent's runtime tool for adding goals -- one managed tool whose
// description/schema can be edited in the web UI and which is bound per agent.
func (t *ToolSet) setGoals() actool.CoreTool {
	return writeTool("set_goals",
		"Add an exploration goal (goal) to [this task]. A goal is a final deliverable or verifiable result, not an attack step or a recon action.\n"+
			"* Prefer batching: put several goals into the goals array and submit them at once; the returned ids have the same length and order (a failed entry has id=0, with details in errors). For a single one, omit goals and give the top-level text directly.\n"+
			"vulnclass is optional: the corresponding vulnerability class (such as SQLi/IDOR); leave it empty for a business logic goal. Whether a goal is achieved is judged and marked met by the system; this tool only adds them.",
		obj(map[string]any{
			"goals":     map[string]any{"type": "array", "description": "[prefer this] the array of goals to add, processed in order. Each element: text (required, one independent verifiable final goal) + vulnclass (optional). The returned ids have the same length and order as this array.", "items": map[string]any{"type": "object"}},
			"text":      str("[single] one independent verifiable final goal"),
			"vulnclass": str("[single] the corresponding vulnerability class if it is clear, such as SQLi/IDOR; a business logic goal may leave it empty"),
		}),
		func(_ context.Context, in json.RawMessage) (actool.Result, error) {
			if t.ts == nil {
				return actool.Errorf("set_goals is not enabled: ExplorationStore is not initialized"), nil
			}
			var a struct {
				Goals    []goalItem `json:"goals"`
				goalItem            // single mode: top-level text/vulnclass
			}
			_ = json.Unmarshal(in, &a)
			batch := len(a.Goals) > 0
			items := a.Goals
			if !batch {
				items = []goalItem{a.goalItem}
			}

			ids := make([]int64, len(items))
			errs := map[string]string{}
			var addedTexts []string
			for i, it := range items {
				id, err := t.addOneGoal(it)
				if err != nil {
					errs[strconv.Itoa(i)] = err.Error()
					continue
				}
				ids[i] = id
				addedTexts = append(addedTexts, strings.TrimSpace(it.Text))
			}
			if len(addedTexts) > 0 {
				// Wake the planner (once for the whole batch). notifyGoal first: one set_goals records one
				// "a human added N goals: ..." trigger rather than flooding one per entry; the decomposer and
				// workers have no such callback -> fall back to a bare notify (the decomposer's round 0 has not
				// even wired notify, i.e. a no-op, because the planner has not started yet).
				switch {
				case t.notifyGoal != nil:
					t.notifyGoal(addedTexts)
				case t.notify != nil:
					t.notify()
				}
				// The main agent adding a goal at runtime -> pull a completed/paused task back to running (the
				// terminal-state gate swallows a plain notify, so it must be revived explicitly). Only mainagent wires this callback; the decomposer and workers pass nil.
				if t.resumeTask != nil {
					t.resumeTask()
				}
			}

			if !batch { // single: keep the original return
				if e, bad := errs["0"]; bad {
					return actool.Errorf(e), nil
				}
				return actool.Text(fmt.Sprintf("goal added: %d", ids[0])), nil
			}
			out := map[string]any{"ids": ids}
			if len(errs) > 0 {
				out["errors"] = errs
			}
			return jsonResult(out)
		})
}

type constraintItem struct {
	Text string `json:"text"`
	Type string `json:"type"` // allow | deny
}

// addOneConstraint persists one operating constraint into task_constraints. origin comes from t.worker
// (defaulting to system): the decomposer writes "goals" and the main agent writes "human".
func (t *ToolSet) addOneConstraint(it constraintItem) (int64, error) {
	text := strings.TrimSpace(it.Text)
	if text == "" {
		return 0, fmt.Errorf("text must not be empty")
	}
	kind := strings.TrimSpace(strings.ToLower(it.Type))
	if kind == "" {
		kind = "deny" // default to forbidding: more conservative when the type is not stated
	}
	if kind != "allow" && kind != "deny" {
		return 0, fmt.Errorf("type must be allow or deny")
	}
	return t.ts.AddConstraint(kind, text, t.worker)
}

